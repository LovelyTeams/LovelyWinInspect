/// 标题栏等处使用的 logo 图片（直接按字节构造，避免 GPUI 把 "logo.png" 误判为 URL）。
pub fn logo_image() -> Option<std::sync::Arc<gpui::Image>> {
    use std::sync::{Arc, OnceLock};
    static LOGO: OnceLock<Option<Arc<gpui::Image>>> = OnceLock::new();
    LOGO.get_or_init(|| LOGO_PNG.map(|b| Arc::new(gpui::Image::from_bytes(gpui::ImageFormat::Png, b.to_vec()))))
        .clone()
}

pub struct Assets;

impl AssetSource for Assets {
    fn load(&self, path: &str) -> Result<Option<Cow<'static, [u8]>>> {
        let name = path
            .trim_start_matches("icons/")
            .trim_end_matches(".svg");
        Ok(icon_body(name).map(|body| {
            let svg = format!(
                r#"<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{body}</svg>"#
            );
            Cow::Owned(svg.into_bytes())
        }))
    }

    fn list(&self, path: &str) -> Result<Vec<SharedString>> {
        if path.starts_with("icons") {
            Ok(ICON_NAMES
                .iter()
                .map(|n| SharedString::from(format!("icons/{n}.svg")))
                .collect())
        } else {
            Ok(Vec::new())
        }
    }
}

pub fn icon_path(name: &str) -> SharedString {
    SharedString::from(format!("icons/{name}.svg"))
}
